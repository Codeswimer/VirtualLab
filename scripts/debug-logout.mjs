import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath:'/usr/bin/google-chrome', args:['--no-sandbox'] });
const page = await browser.newPage({ viewport:{width:1440,height:950} });
page.on('console', m=>console.log('console',m.type(),m.text()));
page.on('pageerror', e=>console.log('pageerror',e.message));
await page.goto('http://localhost:4173/', {waitUntil:'networkidle'});
await page.getByRole('button',{name:/Demo student/i}).click();
await page.waitForTimeout(800);
console.log('after login', page.url());
await page.goto('http://localhost:4173/#/settings', {waitUntil:'networkidle'});
await page.waitForTimeout(500);
console.log('settings', page.url(), await page.locator('main').innerText().then(t=>t.slice(0,80)));
const buttons = await page.getByRole('button',{name:/Sign out/i}).count();
console.log('signout buttons', buttons);
await page.getByRole('button',{name:/Sign out/i}).first().click();
await page.waitForTimeout(1500);
console.log('after signout', page.url());
console.log((await page.locator('body').innerText()).slice(0,200));
await page.screenshot({path:'/tmp/vlab-shots/debug-logout.png', fullPage:true});
await browser.close();
